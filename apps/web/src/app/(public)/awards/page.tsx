import type { Metadata } from 'next';
import { EmptyState } from '@/components/EmptyState';
import { SectionHeading } from '@/components/SectionHeading';
import { editionHeading, pluralise } from '@/lib/format';
import { getLatestAwards } from '@/lib/queries';
import { getPublicSettings, siteUrl } from '@/lib/settings';
import type { AwardView } from '@/lib/types';
import styles from './page.module.css';

export const revalidate = 60;

interface AwardGroup {
  date: string | null;
  awards: AwardView[];
}

/** `getLatestAwards` is newest-first, so grouping in a single pass keeps that order. */
function groupByEdition(awards: AwardView[]): AwardGroup[] {
  const groups: AwardGroup[] = [];
  for (const award of awards) {
    const last = groups[groups.length - 1];
    if (last && last.date === award.editionDate) last.awards.push(award);
    else groups.push({ date: award.editionDate, awards: [award] });
  }
  return groups;
}

function categoryLabel(category: string | null): string {
  if (!category) return 'Award';
  if (category === 'weekly') return 'Weekly award';
  return category;
}

export async function generateMetadata(): Promise<Metadata> {
  const settings = await getPublicSettings();
  const baseUrl = siteUrl(settings);
  const description = `The weekly awards handed out to contributors to ${settings.site.name}. Chosen by the AI desk from the week's published stories, and only ever from real bylines.`;

  return {
    title: 'Awards',
    description,
    alternates: { canonical: `${baseUrl}/awards` },
    openGraph: {
      type: 'website',
      siteName: settings.site.name,
      title: `Awards — ${settings.site.name}`,
      description,
      url: `${baseUrl}/awards`,
    },
  };
}

export default async function AwardsPage(): Promise<React.JSX.Element> {
  const [settings, awards] = await Promise.all([getPublicSettings(), getLatestAwards(40)]);
  const timeZone = settings.site.timezone;
  const groups = groupByEdition(awards);

  return (
    <div className="container">
      <header className="page-head">
        <div className="accent-bar" aria-hidden="true" />
        <p className="eyebrow">Weekly, and only from real bylines</p>
        <h1>Awards</h1>
        <p className="lede">
          Awards are written from the week&rsquo;s published stories by the AI desk. Winners are
          always named contributors who actually filed that week; the desk refuses to invent a
          winner to fill the slate.
        </p>
      </header>

      {groups.length > 0 ? (
        groups.map((group, index) => {
          const headingId = `awards-${group.date ?? 'undated'}`;
          return (
            <section className={styles.group} key={group.date ?? `undated-${index}`}>
              <h2 className={styles.groupTitle} id={headingId}>
                {group.date ? editionHeading(group.date, timeZone) : 'Undated awards'}
                <span className={styles.groupCount}>{pluralise(group.awards.length, 'award')}</span>
              </h2>

              <ul className={styles.list} aria-labelledby={headingId}>
                {group.awards.map((award) => (
                  <li key={award.id}>
                    <article className={styles.award}>
                      <p className={styles.awardMeta}>
                        <span>{categoryLabel(award.category)}</span>
                        {award.autoGenerated ? (
                          <span className="badge badge--info">AI-written</span>
                        ) : null}
                      </p>

                      <h3 className={styles.awardTitle}>{award.title}</h3>

                      <p className={styles.winner}>
                        <span className={styles.winnerLabel}>Winner</span>
                        {award.winnerName}
                      </p>

                      {award.citation ? (
                        <p className={styles.citation}>{award.citation}</p>
                      ) : (
                        <p className={`${styles.citation} muted`}>
                          No citation was filed with this award.
                        </p>
                      )}
                    </article>
                  </li>
                ))}
              </ul>
            </section>
          );
        })
      ) : (
        <EmptyState
          title="No awards yet"
          message="A weekly round needs at least three eligible contributors and three published stories before it runs. When there are not enough, the desk writes nothing rather than inventing winners."
          actionHref="/submit"
          actionLabel="Submit a story"
        />
      )}

      <section className="section" aria-labelledby="awards-how-heading">
        <SectionHeading id="awards-how-heading" title="How the awards work" />
        <ul className={styles.rules}>
          <li>
            The round looks at stories published in the last seven days and at the contributors
            credited on them. Anonymous bylines are not put up for awards.
          </li>
          <li>
            The AI desk proposes titles, winners and citations, but every winner must match a real
            contributor from that week. Unmatched names are dropped, not published.
          </li>
          <li>
            Every automatic award is marked <strong>AI-written</strong>. Awards without that badge
            were added by hand in the console.
          </li>
          <li>
            Awards name people, not story links. An award does not create a byline that was not
            already on a published story.
          </li>
        </ul>
      </section>
    </div>
  );
}
