/** Row + view types shared by the website's data layer. */

export type SubmissionStatus =
  'received' | 'processing' | 'queued_review' | 'published' | 'rejected' | 'failed';

export interface PublicSettings {
  site: {
    name: string;
    tagline: string;
    description: string;
    url: string;
    timezone: string;
    contactDiscord: string;
  };
  submissions: {
    anonymousAllowed: boolean;
    requireSourceUrl: boolean;
    minStoryChars: number;
    maxStoryChars: number;
    maxHeadlineChars: number;
    maxImages: number;
    maxImageMb: number;
  };
  content: { breakingEnabled: boolean };
  appearance: { frontPageLimit: number; showAwards: boolean; tickerCount: number };
  community: { votingEnabled: boolean; reviewsEnabled: boolean; reviewMaxChars: number };
}

export interface ArticleVoteCounts {
  articleId: string;
  likes: number;
  dislikes: number;
  myVote: -1 | 1 | null;
  authenticated: boolean;
}

export interface ReviewSummary {
  count: number;
  average: number;
  distribution: Array<{ rating: number; count: number }>;
}

export interface CommunityReview {
  id: string;
  displayName: string | null;
  avatarUrl: string | null;
  rating: number;
  body: string;
  status: 'published' | 'pending' | 'hidden';
  createdAt: string;
  updatedAt: string;
}

export interface CommunityViewer {
  displayName: string;
  avatarUrl: string | null;
}

export interface ReviewListResponse {
  articleId: string;
  summary: ReviewSummary;
  reviews: CommunityReview[];
  hasMore: boolean;
  myReview: CommunityReview | null;
  authenticated: boolean;
  viewer: CommunityViewer | null;
}

export interface ReviewSubmitResponse {
  review: CommunityReview;
  summary: ReviewSummary;
  published: boolean;
  message: string;
  authenticated: boolean;
}

export interface ReviewDeleteResponse {
  ok: true;
  summary: ReviewSummary;
}

export interface CategoryView {
  slug: string;
  name: string;
  description: string | null;
  accent: string | null;
  sortOrder: number;
  publishedCount: number;
}

export interface ArticleListItem {
  id: string;
  slug: string;
  headline: string;
  dek: string | null;
  excerpt: string;
  categorySlug: string;
  categoryName: string;
  categoryAccent: string | null;
  authorDisplay: string;
  identityMode: 'named' | 'discord' | 'anonymous';
  tags: string[];
  breaking: boolean;
  featured: boolean;
  placement: 'lead' | 'top' | 'standard';
  readingMinutes: number;
  editionDate: string;
  publishedAt: string | null;
  sourceUrl: string | null;
  image: ArticleImageView | null;
  imageCount: number;
}

export interface ArticleImageView {
  id: string;
  url: string;
  thumbUrl: string | null;
  width: number | null;
  height: number | null;
  caption: string | null;
  alt: string | null;
  attribution: string | null;
}

export interface ArticleDetail extends ArticleListItem {
  body: string;
  editorNote: string | null;
  aiModel: string | null;
  aiGenerated: boolean;
  images: ArticleImageView[];
}

export interface EditionView {
  editionDate: string;
  headline: string | null;
  summary: string | null;
  mood: string | null;
  articleCount: number;
  leadArticleId: string | null;
  generatedBy: string;
  status: 'draft' | 'published';
  updatedAt: string;
}

export interface AwardView {
  id: string;
  title: string;
  category: string | null;
  winnerName: string;
  citation: string | null;
  editionDate: string | null;
  articleId: string | null;
  autoGenerated: boolean;
  sortOrder: number;
}

export interface SubmissionDetail {
  id: string;
  headline: string;
  status: SubmissionStatus;
  statusCopy: string;
  reviewReasons: string[];
  aiError: string | null;
  article: {
    id: string;
    slug: string;
    headline: string;
    category: string;
    publishedAt: string | null;
    breaking: boolean;
  } | null;
  images: Array<{ id: string; url: string; thumbUrl: string | null }>;
  createdAt: string;
  updatedAt: string;
}

export interface ApiErrorBody {
  code: string;
  message: string;
  details?: unknown;
  issues?: Array<{ field: string; message: string }>;
}

export interface Page<T> {
  items: T[];
  total: number;
  limit: number;
  offset: number;
}
